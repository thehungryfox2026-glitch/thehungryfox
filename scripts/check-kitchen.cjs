const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const code = fs.readFileSync('worker.js', 'utf8');
const start = code.indexOf('const KITCHEN_HTML=');
assert.ok(start >= 0, 'Kitchen HTML constant must exist');
const line = code.slice(start).split('\n', 1)[0];
const encoded = line.slice('const KITCHEN_HTML='.length, -1);
const html = JSON.parse(encoded);
const scriptStart = html.indexOf('<script>');
const scriptEnd = html.indexOf('</script>', scriptStart);
assert.ok(scriptStart >= 0 && scriptEnd > scriptStart, 'Dashboard script must exist');
new vm.Script(html.slice(scriptStart + 8, scriptEnd), {filename:'kitchen-dashboard.js'});
assert.ok(html.includes("className='receipt-logo'"), 'Approved fox logo must be embedded in each order receipt');
assert.ok(html.includes('.order.print-target .receipt-logo{display:block!important'), 'Fox logo must be visible when printing');
assert.ok(html.includes('.order.print-target:before{display:none!important}'), 'Duplicate text-only logo heading must be hidden when printing');
assert.ok(html.includes('FLAVOURS / OPTIONS: '), 'All item flavour and option labels must be printed');
assert.ok(html.includes("return 'DESSERTS'"), 'Desserts must have their own receipt category');
assert.ok(html.includes('singara|samosa|spring roll|bao'), 'Side dishes must be grouped under sides and extras');
assert.ok(html.includes('@page{size:58mm auto'), 'Receipt must target 58mm thermal paper');
assert.ok(html.includes('id="sound-enabled"'), 'Kitchen dashboard must include a sound-alert toggle');
assert.ok(html.includes('id="test-sound"'), 'Kitchen dashboard must include a test-sound control');
assert.ok(html.includes('function playOrderAlert()'), 'New-order sound alert function must exist');
assert.ok(html.includes("osc.type='square'"), 'Kitchen order alert must use a sharper, more audible alarm tone');
assert.ok(html.includes('exponentialRampToValueAtTime(0.62'), 'Kitchen order alert volume envelope must be substantially louder');
assert.ok(html.includes('const notes=[880,1175,880,1175,1397,1175,880,1175,1397]'), 'Kitchen order alert must play a repeated urgent multi-tone sequence');
assert.ok(html.includes('knownOrderIds!==null'), 'Sound must only alert for orders arriving after initial dashboard load');
assert.ok(html.includes('id="print-test"'), 'Kitchen dashboard must include a 58mm print-test control');
assert.ok(html.includes('PRINT TEST ONLY — NOT AN ORDER'), 'Print test must be clearly marked as not a real order');
assert.ok(html.includes('Printing: manual'), 'Dashboard must clearly state printing is manual, not automatic');
assert.ok(html.includes('localStorage.setItem(\'hungryfox-kitchen-sound\''), 'Sound preference must persist on this device');
assert.ok(code.includes('await savePaidKitchenOrder(s,env)'), 'Webhook order storage missing');
assert.ok(code.includes('kitchenAuthorized(req,env)'), 'Kitchen authorization missing');
assert.ok(code.includes("SELECT * FROM orders WHERE payment_status='paid'"), 'Kitchen query missing');
const site = fs.readFileSync('index.html', 'utf8');
assert.ok(site.includes('id="website-offer-banner"'), 'Website offer banner must exist');
assert.ok(site.includes('Website Exclusive Offers'), 'Website offer heading must be visible');
assert.ok(site.includes('10% OFF') && site.includes('15% OFF'), 'Both website offer tiers must be displayed');
assert.ok(site.includes('id="cart-discount-row"') && site.includes('id="checkout-discount-row"'), 'Discount must be shown in basket and checkout totals');
assert.ok(site.includes('function getWebsiteBasketDiscount'), 'Frontend basket discount calculation must exist');
assert.ok(code.includes('websiteDiscountPercent=reward?0:'), 'Fox Rewards must not stack with basket promotions');
assert.ok(code.includes('https://api.stripe.com/v1/coupons'), 'Server must create a Stripe coupon for eligible website offers');
assert.ok(code.includes('discounts[0][coupon]'), 'Stripe Checkout must receive the automatic basket discount');
assert.ok(code.includes('subtotal>=3000?15:(subtotal>=2000?10:0)'), 'Server must enforce 15% at £30 and 10% at £20');
const inlineScripts = site.split('<script').slice(1).map(block => block.slice(block.indexOf('>') + 1, block.indexOf('</script>'))).filter(script => script.trim());
for (let i = 0; i < inlineScripts.length; i++) new vm.Script(inlineScripts[i], {filename:'website-inline-'+i+'.js'});
console.log('Kitchen code syntax and route checks passed');
